import { type FormEvent, type KeyboardEvent, useState } from "react";

import { ApiError, api } from "../api/client";
import { JOB_PRIORITIES, type JobAccepted, type JobPriority } from "../api/types";
import RecentSubmissions from "../components/RecentSubmissions";
import { useRecentSubmissions } from "../hooks/useRecentSubmissions";
import { formatPayload, JOB_PRESETS } from "../lib/presets";
import { checkDraft, type FieldErrors, WIRE_FIELDS } from "../lib/validateSubmission";

const DEFAULT_MAX_ATTEMPTS = 5;

interface Rejection {
  message: string;
  // Set on a 409: the job that already holds this ID.
  existingJobId?: string;
}

export default function SubmitPage() {
  const [jobId, setJobId] = useState("");
  const [jobType, setJobType] = useState(JOB_PRESETS[0].jobType);
  const [priority, setPriority] = useState<JobPriority>("normal");
  const [maxAttempts, setMaxAttempts] = useState(String(DEFAULT_MAX_ATTEMPTS));
  const [payloadText, setPayloadText] = useState(formatPayload(JOB_PRESETS[0].payload));

  const [submitting, setSubmitting] = useState(false);
  const [error, setError] = useState<Rejection | null>(null);
  // Field errors from the API's 422. Each is cleared once that field is
  // edited, because the server's verdict was about the old value.
  const [serverErrors, setServerErrors] = useState<FieldErrors>({});
  const [accepted, setAccepted] = useState<JobAccepted | null>(null);
  // Errors stay hidden until the first submit, so the form does not open by
  // scolding someone who has not finished typing.
  const [attempted, setAttempted] = useState(false);
  const recent = useRecentSubmissions();

  const check = checkDraft({ jobId, jobType, maxAttempts, payloadText });
  const shown: FieldErrors = { ...serverErrors, ...(attempted ? check.errors : {}) };
  const isValid = Object.keys(check.errors).length === 0;

  const applyPreset = (index: number) => {
    const preset = JOB_PRESETS[index];
    setJobType(preset.jobType);
    setPayloadText(formatPayload(preset.payload));
    setError(null);
    setServerErrors({});
  };

  const edit = (field: keyof FieldErrors, setter: (value: string) => void, value: string) => {
    setter(value);
    if (serverErrors[field]) {
      setServerErrors(({ [field]: _cleared, ...rest }) => rest);
    }
  };

  // Reaching for the mouse after editing a large payload is the slow part of
  // sending test jobs. requestSubmit runs the form's own submit handler, so
  // the same checks apply as for the button. It ignores the button's disabled
  // attribute, which is why the in flight guard is repeated here.
  const submitOnShortcut = (event: KeyboardEvent<HTMLTextAreaElement>) => {
    if (event.key === "Enter" && (event.ctrlKey || event.metaKey)) {
      event.preventDefault();
      if (!submitting) {
        event.currentTarget.form?.requestSubmit();
      }
    }
  };

  const submit = async (event: FormEvent) => {
    event.preventDefault();
    setError(null);
    setServerErrors({});
    setAccepted(null);
    setAttempted(true);

    const { payload } = check;
    if (!isValid || !payload) {
      return;
    }

    setSubmitting(true);
    try {
      const result = await api.submitJob({
        job_id: jobId.trim() || undefined,
        job_type: jobType.trim(),
        priority,
        max_attempts: Number(maxAttempts),
        payload,
      });
      setAccepted(result);
      recent.add({
        jobId: result.job_id,
        jobType: jobType.trim(),
        submittedAt: new Date().toISOString(),
      });
    } catch (caught) {
      const fieldErrors = caught instanceof ApiError ? toFormErrors(caught.fieldErrors) : {};
      setServerErrors(fieldErrors);
      setError(describeRejection(caught, jobId.trim(), Object.keys(fieldErrors).length > 0));
    } finally {
      setSubmitting(false);
    }
  };

  return (
    <div className="detail">
      <section className="card">
        <h2 className="card-title">Start from an example</h2>
        <div className="presets">
          {JOB_PRESETS.map((preset, index) => (
            <button
              key={preset.jobType}
              type="button"
              className={`preset${preset.jobType === jobType ? " preset-active" : ""}`}
              onClick={() => applyPreset(index)}
            >
              <strong>{preset.label}</strong>
              <span className="muted">{preset.description}</span>
            </button>
          ))}
        </div>
      </section>

      <form className="card form" onSubmit={submit}>
        <div className="form-row">
          <label className="wide-field">
            Job ID (optional)
            <input
              className="mono"
              placeholder="Generated by the API if left empty"
              value={jobId}
              aria-invalid={Boolean(shown.jobId)}
              onChange={(event) => edit("jobId", setJobId, event.target.value)}
            />
            {shown.jobId && <span className="field-error">{shown.jobId}</span>}
          </label>
          <label>
            Job type
            <input
              value={jobType}
              aria-invalid={Boolean(shown.jobType)}
              onChange={(event) => edit("jobType", setJobType, event.target.value)}
            />
            {shown.jobType && <span className="field-error">{shown.jobType}</span>}
          </label>
          <label>
            Priority
            <select
              value={priority}
              onChange={(event) => setPriority(event.target.value as JobPriority)}
            >
              {JOB_PRIORITIES.map((value) => (
                <option key={value} value={value}>
                  {value}
                </option>
              ))}
            </select>
          </label>
          <label>
            Max attempts
            <input
              type="number"
              min={1}
              max={20}
              value={maxAttempts}
              aria-invalid={Boolean(shown.maxAttempts)}
              onChange={(event) => edit("maxAttempts", setMaxAttempts, event.target.value)}
            />
            {shown.maxAttempts && <span className="field-error">{shown.maxAttempts}</span>}
          </label>
        </div>
        {/* Not wrapped in a label like the other fields: a button inside a
            label forwards its clicks to the textarea. */}
        <div className="field">
          <div className="field-header">
            <label htmlFor="payload">Payload</label>
            <button
              type="button"
              className="small-button"
              disabled={!check.payload}
              title="Re-indent the payload. Needs valid JSON."
              onClick={() => check.payload && setPayloadText(formatPayload(check.payload))}
            >
              Format JSON
            </button>
          </div>
          <textarea
            id="payload"
            className="payload-editor"
            spellCheck={false}
            rows={16}
            value={payloadText}
            aria-invalid={Boolean(shown.payloadText)}
            aria-describedby="payload-hint"
            onChange={(event) => edit("payloadText", setPayloadText, event.target.value)}
            onKeyDown={submitOnShortcut}
          />
          {shown.payloadText ? (
            <span className="field-error">{shown.payloadText}</span>
          ) : (
            <span id="payload-hint" className="muted field-hint">
              Ctrl+Enter or Cmd+Enter submits from here.
            </span>
          )}
        </div>

        {check.warnings.map((warning) => (
          <p key={warning} className="warning">
            {warning}
          </p>
        ))}

        {error && (
          <p className="error">
            {error.message}
            {error.existingJobId && (
              <>
                {" "}
                <a href={`#/jobs/${error.existingJobId}`}>Open the existing job</a>
              </>
            )}
          </p>
        )}

        <div className="form-actions">
          <button
            type="submit"
            className="primary-button"
            disabled={submitting || (attempted && !isValid)}
          >
            {submitting ? "Submitting" : "Submit job"}
          </button>
        </div>
      </form>

      {accepted && (
        <section className="card success-card">
          <h2 className="card-title">Job queued</h2>
          <p>
            <a href={`#/jobs/${accepted.job_id}`} className="mono">
              {accepted.job_id}
            </a>{" "}
            is on the stream as message <span className="mono">{accepted.stream_message_id}</span>.
          </p>
        </section>
      )}

      <RecentSubmissions entries={recent.entries} onClear={recent.clear} />
    </div>
  );
}

function toFormErrors(wireErrors: Record<string, string>): FieldErrors {
  const errors: FieldErrors = {};
  for (const [wire, message] of Object.entries(wireErrors)) {
    const field = WIRE_FIELDS[wire];
    if (field) {
      errors[field] = message;
    }
  }
  return errors;
}

function describeRejection(caught: unknown, jobId: string, onFields: boolean): Rejection {
  if (caught instanceof ApiError && caught.status === 409) {
    // The ID is the idempotency key. A 409 means this exact job was already
    // accepted, so resending it is safe and nothing was queued twice.
    return {
      message: "A job with this ID was already submitted, so nothing new was queued.",
      existingJobId: jobId || undefined,
    };
  }
  if (caught instanceof ApiError && caught.status === 422 && onFields) {
    return { message: "The API rejected the submission. See the highlighted fields." };
  }
  return { message: caught instanceof Error ? caught.message : String(caught) };
}
